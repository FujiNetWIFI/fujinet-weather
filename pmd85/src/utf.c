char * utf8_to_ascii(char *s)
{
    static unsigned char *p1;
    static unsigned char *p2;
    static short hex;

    p1 = p2 = (unsigned char *)s;
    while (*p1) {
        if (*p1 >= 0xC0) {
            hex = ((*p1++ - 0xC2) << 6) + *p1++;
            if (hex > 191 && hex < 577) {
                *p2++ = utf2ascii[hex - 192];
            } else {
                *p2++ = '_';
            }
        } else {
            *p2++ = *p1++;
        }
    }
    *p2 = '\0';
    return s;
}
